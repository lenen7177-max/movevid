#!/usr/bin/env node
// Writes the per-site files from site.config.jsonc:
//   apps/server/wrangler.jsonc, apps/web/wrangler.jsonc  ← their wrangler.template.jsonc
//   apps/web/public/manifest.webmanifest                 ← name / short_name
//   packages/app-config/src/site.generated.json          ← name, domain, support email
//   node scripts/site-sync.mjs           write them (`pnpm site:sync`)
//   node scripts/site-sync.mjs --check   exit 1 when any is out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseJsonc } from "./lib/jsonc.mjs";
import { isPlaceholder } from "./lib/placeholders.mjs";

export const SITE_CONFIG_FILE = "site.config.jsonc";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

const WRANGLER_OUTPUTS = [
  { template: "apps/server/wrangler.template.jsonc", output: "apps/server/wrangler.jsonc" },
  { template: "apps/web/wrangler.template.jsonc", output: "apps/web/wrangler.jsonc" },
];
const MANIFEST_FILE = "apps/web/public/manifest.webmanifest";
const APP_CONFIG_SITE_FILE = "packages/app-config/src/site.generated.json";

/** Every file `pnpm site:sync` writes. */
export const GENERATED_FILES = [
  ...WRANGLER_OUTPUTS.map(({ output }) => output),
  MANIFEST_FILE,
  APP_CONFIG_SITE_FILE,
];

const GENERATED_HEADER = (template) =>
  [
    `// Generated by \`pnpm site:sync\` from ${SITE_CONFIG_FILE} and ${template}.`,
    "// Do not edit: change those files and run `pnpm site:sync` again.",
  ].join("\n");

const KEYS = {
  root: [
    "name",
    "shortName",
    "domain",
    "supportEmail",
    "mediaUrl",
    "cloudflare",
    "turnstileSiteKey",
    "public",
  ],
  cloudflare: [
    "webWorker",
    "serverWorker",
    "d1DatabaseName",
    "d1DatabaseId",
    "r2Bucket",
    "rateLimitNamespaceIds",
  ],
  rateLimitNamespaceIds: ["authEmailIp", "authEmailAddress"],
  public: [
    "githubClientId",
    "googleClientId",
    "gaMeasurementId",
    "openpanelClientId",
    "tawkPropertyId",
    "tawkWidgetId",
    "apimartAssetGroupId",
  ],
};

const WORKER_NAME = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
const BUCKET_NAME = /^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/;
// The last label may be punycode, the form internationalized TLDs (xn--…) take in Cloudflare.
const DOMAIN =
  /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+(?:[a-z]{2,63}|xn--[a-z0-9-]{1,59})$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const EMAIL = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
const POSITIVE_INTEGER = /^[1-9]\d{0,15}$/;

export function readSiteConfig(root = ROOT) {
  return parseJsonc(readFileSync(resolve(root, SITE_CONFIG_FILE), "utf8"));
}

/**
 * Problems with site.config.jsonc, as readable lines. Values that are still placeholders are
 * left to the placeholder check, so each problem is reported once.
 */
export function validateSiteConfig(config) {
  const issues = [];
  const at = (path) => `${SITE_CONFIG_FILE}: ${path}`;
  const unknownKeys = (value, allowed, path) => {
    for (const key of Object.keys(value ?? {})) {
      if (!allowed.includes(key)) issues.push(`${at(path + key)} is not a known setting`);
    }
  };
  const string = (value, path, { required = true, pattern, hint } = {}) => {
    if (value === undefined || value === "") {
      if (required) issues.push(`${at(path)} is required`);
      return;
    }
    if (typeof value !== "string") {
      issues.push(`${at(path)} must be a string`);
      return;
    }
    if (pattern && !isPlaceholder(value) && !pattern.test(value)) {
      issues.push(`${at(path)} "${value}" ${hint}`);
    }
  };

  if (!config || typeof config !== "object" || Array.isArray(config)) {
    return [`${SITE_CONFIG_FILE} must be an object`];
  }
  unknownKeys(config, KEYS.root, "");
  string(config.name, "name");
  string(config.shortName, "shortName", { required: false });
  string(config.domain, "domain", {
    pattern: DOMAIN,
    hint: "must be a lowercase apex domain like mysite.com (no https://, www. or path)",
  });
  if (typeof config.domain === "string" && config.domain.startsWith("www.")) {
    issues.push(`${at("domain")} should be the apex domain; www.<domain> is bound automatically`);
  }
  string(config.supportEmail, "supportEmail", {
    required: false,
    pattern: EMAIL,
    hint: "must be an email address",
  });
  string(config.mediaUrl, "mediaUrl", {
    pattern: /^https:\/\/[^\s/]+(?:\/\S*)?$/,
    hint: "must be an https:// URL",
  });
  string(config.turnstileSiteKey, "turnstileSiteKey");

  const cloudflare = config.cloudflare;
  if (!cloudflare || typeof cloudflare !== "object") {
    issues.push(`${at("cloudflare")} is required`);
  } else {
    unknownKeys(cloudflare, KEYS.cloudflare, "cloudflare.");
    const workerHint = "must be lowercase letters, digits and dashes (at most 63)";
    string(cloudflare.webWorker, "cloudflare.webWorker", {
      pattern: WORKER_NAME,
      hint: workerHint,
    });
    string(cloudflare.serverWorker, "cloudflare.serverWorker", {
      pattern: WORKER_NAME,
      hint: workerHint,
    });
    if (cloudflare.webWorker && cloudflare.webWorker === cloudflare.serverWorker) {
      issues.push(`${at("cloudflare.webWorker")} and serverWorker must be different workers`);
    }
    string(cloudflare.d1DatabaseName, "cloudflare.d1DatabaseName");
    string(cloudflare.d1DatabaseId, "cloudflare.d1DatabaseId", {
      pattern: UUID,
      hint: "must be the UUID printed by `wrangler d1 create`",
    });
    string(cloudflare.r2Bucket, "cloudflare.r2Bucket", {
      pattern: BUCKET_NAME,
      hint: "must be 3–63 lowercase letters, digits and dashes",
    });

    const limits = cloudflare.rateLimitNamespaceIds;
    if (!limits || typeof limits !== "object") {
      issues.push(`${at("cloudflare.rateLimitNamespaceIds")} is required`);
    } else {
      unknownKeys(limits, KEYS.rateLimitNamespaceIds, "cloudflare.rateLimitNamespaceIds.");
      const seen = new Map();
      for (const key of KEYS.rateLimitNamespaceIds) {
        const path = `cloudflare.rateLimitNamespaceIds.${key}`;
        const value = limits[key];
        if (value === undefined || value === "") {
          issues.push(`${at(path)} is required`);
          continue;
        }
        const id = String(value);
        if (isPlaceholder(id)) continue;
        if (!POSITIVE_INTEGER.test(id)) {
          issues.push(`${at(path)} "${id}" must be a positive integer`);
        } else if (seen.has(id)) {
          issues.push(`${at(path)} reuses namespace id ${id} of ${seen.get(id)}`);
        }
        seen.set(id, key);
      }
    }
  }

  if (config.public !== undefined) {
    if (typeof config.public !== "object" || config.public === null) {
      issues.push(`${at("public")} must be an object`);
    } else {
      unknownKeys(config.public, KEYS.public, "public.");
      for (const key of KEYS.public) {
        string(config.public[key], `public.${key}`, { required: false });
      }
    }
  }
  return issues;
}

/** The {{token}} values used by the wrangler templates. */
export function siteTokens(config) {
  const cloudflare = config.cloudflare ?? {};
  const limits = cloudflare.rateLimitNamespaceIds ?? {};
  const publicIds = config.public ?? {};
  return {
    name: config.name,
    domain: config.domain,
    wwwHost: `www.${config.domain}`,
    apiHost: `api.${config.domain}`,
    siteUrl: `https://${config.domain}`,
    apiUrl: `https://api.${config.domain}`,
    mediaUrl: String(config.mediaUrl ?? "").replace(/\/+$/, ""),
    supportEmail: config.supportEmail || `support@${config.domain}`,
    webWorker: cloudflare.webWorker,
    serverWorker: cloudflare.serverWorker,
    d1DatabaseName: cloudflare.d1DatabaseName,
    d1DatabaseId: cloudflare.d1DatabaseId,
    r2Bucket: cloudflare.r2Bucket,
    rateLimitIpNamespaceId: String(limits.authEmailIp ?? ""),
    rateLimitAddressNamespaceId: String(limits.authEmailAddress ?? ""),
    turnstileSiteKey: config.turnstileSiteKey,
    githubClientId: publicIds.githubClientId ?? "",
    googleClientId: publicIds.googleClientId ?? "",
    gaMeasurementId: publicIds.gaMeasurementId ?? "",
    openpanelClientId: publicIds.openpanelClientId ?? "",
    tawkPropertyId: publicIds.tawkPropertyId ?? "",
    tawkWidgetId: publicIds.tawkWidgetId ?? "",
    apimartAssetGroupId: publicIds.apimartAssetGroupId ?? "",
  };
}

/** Text with LF line endings (a Windows checkout with core.autocrlf has CRLF). */
const lf = (text) => text.replace(/\r\n/g, "\n");

/** A wrangler template with its {{tokens}} filled in; tokens always sit inside JSON strings. */
export function renderTemplate(template, tokens, templateName = "template") {
  const body = lf(template)
    .split("\n")
    .filter((line) => !line.startsWith("//#"))
    .join("\n")
    .replace(/\{\{\s*(\w+)\s*\}\}/g, (_match, key) => {
      if (!(key in tokens)) throw new Error(`${templateName}: unknown token {{${key}}}`);
      return JSON.stringify(String(tokens[key] ?? "")).slice(1, -1);
    });
  const leftover = /\{\{[^}\n]*\}?\}?/.exec(body);
  if (leftover) throw new Error(`${templateName}: malformed token ${leftover[0]}`);
  return `${GENERATED_HEADER(templateName)}\n${body.replace(/^\n+/, "")}`;
}

/** Every generated file's expected content, keyed by its path from the repo root. */
export function renderSiteFiles(config, root = ROOT) {
  const tokens = siteTokens(config);
  const files = new Map();
  for (const { template, output } of WRANGLER_OUTPUTS) {
    files.set(
      output,
      renderTemplate(readFileSync(resolve(root, template), "utf8"), tokens, template),
    );
  }

  const manifest = JSON.parse(readFileSync(resolve(root, MANIFEST_FILE), "utf8"));
  manifest.name = tokens.name;
  manifest.short_name = config.shortName || tokens.name;
  files.set(MANIFEST_FILE, `${JSON.stringify(manifest, null, 2)}\n`);

  const site = { name: tokens.name, domain: tokens.domain, supportEmail: tokens.supportEmail };
  files.set(APP_CONFIG_SITE_FILE, `${JSON.stringify(site, null, 2)}\n`);
  return files;
}

/** Generated files whose content on disk differs from what site.config.jsonc produces. */
export function staleSiteFiles(config, root = ROOT) {
  const stale = [];
  for (const [path, content] of renderSiteFiles(config, root)) {
    const file = resolve(root, path);
    if (!existsSync(file) || lf(readFileSync(file, "utf8")) !== content) stale.push(path);
  }
  return stale;
}

function main() {
  const check = process.argv.includes("--check");
  let config;
  try {
    config = readSiteConfig();
  } catch (error) {
    console.error(`✗ ${SITE_CONFIG_FILE}: ${error.message}`);
    process.exit(1);
  }
  const issues = validateSiteConfig(config);
  if (issues.length) {
    console.error(`✗ Fix ${SITE_CONFIG_FILE} first:\n  ${issues.join("\n  ")}`);
    process.exit(1);
  }

  if (check) {
    const stale = staleSiteFiles(config);
    if (stale.length) {
      console.error(`✗ Out of date with ${SITE_CONFIG_FILE}; run \`pnpm site:sync\`:`);
      for (const path of stale) console.error(`    ${path}`);
      process.exit(1);
    }
    console.log(`✓ Generated files match ${SITE_CONFIG_FILE}.`);
    return;
  }

  for (const [path, content] of renderSiteFiles(config)) {
    const file = resolve(ROOT, path);
    const changed = !existsSync(file) || lf(readFileSync(file, "utf8")) !== content;
    if (changed) writeFileSync(file, content);
    console.log(`${changed ? "wrote    " : "unchanged"} ${path}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
